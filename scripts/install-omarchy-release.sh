#!/bin/bash
set -euo pipefail
export LC_ALL=C
version=4.5.0-3

# Refuse to silently consume a later release from the rolling package repo.
python - "$version" <<'PY'
import re, subprocess, sys
for package in ("omarchy", "omarchy-settings"):
    info = subprocess.check_output(["pacman", "-Si", package], text=True)
    version = re.search(r"^Version\s*:\s*(\S+)", info, re.M).group(1)
    if version != sys.argv[1]:
        raise SystemExit(f"Expected {package} {sys.argv[1]}, repository offers {version}")
PY

# Keep the official package dependencies, but mask their boot-maintenance hooks:
# this container has no EFI system partition or kernel of its own to update.
install -d /etc/pacman.d/kasm-hooks
ln -sf /dev/null /etc/pacman.d/kasm-hooks/80-limine-efi-deploy.hook
ln -sf /dev/null /etc/pacman.d/kasm-hooks/90-mkinitcpio-install.hook
python <<'PY'
from pathlib import Path
path = Path('/etc/pacman.conf')
config = path.read_text()
if '/etc/pacman.d/kasm-hooks' not in config:
    config = config.replace('\n[core]', '\nHookDir = /etc/pacman.d/hooks\nHookDir = /etc/pacman.d/kasm-hooks\n\n[core]', 1)
    path.write_text(config)
PY

installed=$(pacman -Q omarchy 2>/dev/null || true)
if [[ $installed != "omarchy $version" ]]; then
  # Fetch and verify package integrity before replacing the unowned source tree.
  pacman -Sw --noconfirm omarchy omarchy-settings
  if pacman -Q ttf-jetbrains-mono-nerd >/dev/null 2>&1; then
    pacman -R --noconfirm ttf-jetbrains-mono-nerd
  fi
  # These are generated by the earlier image build, not user profile files.
  for command in /usr/local/bin/*; do
    if [[ -L $command && $(readlink "$command") == /usr/share/omarchy/bin/* ]]; then
      rm "$command"
    fi
  done
  rm -rf /usr/share/omarchy
  rm -f /usr/share/fonts/omarchy/omarchy.ttf
  rm -f /usr/share/xdg-terminal-exec/hyprland-xdg-terminals.list
  pacman -S --noconfirm omarchy omarchy-settings
fi

# Keep Kasm's new-profile template from copying the obsolete git checkout.
rm -rf /home/kasm-default-profile/.local/share/omarchy
cp /usr/share/omarchy/applications/foot.desktop /usr/local/share/applications/foot.desktop
fc-cache -f
test "$(pacman -Q omarchy)" = "omarchy $version"
test "$(pacman -Q omarchy-settings)" = "omarchy-settings $version"
OMARCHY_PATH=/usr/share/omarchy /usr/bin/omarchy-version
